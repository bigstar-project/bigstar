void Runtime::ResetForRestart(melonDS::u32 noFrameLimit)
{
    LocalInputs.clear();
    RemoteInputs.clear();
    RollbackInputs.ClearPredictions();
    LastReceivedInputFrame = noFrameLimit;
    LastSentInputFrame = noFrameLimit;
    LastTracedSentInputFrame = noFrameLimit;
    LastTracedReceivedInputFrame = noFrameLimit;
    LastInputHealthSummaryFrame = noFrameLimit;
    LastInputHealthRemoteWaitFrame = noFrameLimit;
    LastInputHealthThrottleFrame = noFrameLimit;
    LastInputHealthThrottleResolvedFrame = noFrameLimit;
    LastInputHealthReceiveGapFrame = noFrameLimit;
    LastInputHealthSendGapFrame = noFrameLimit;
    LastInputFrameThrottleTraceFrame = noFrameLimit;
    LastInputFrameLeadResendAt = {};
    InputFrameLeadResendCount = 0;
}

RemoteInputStoreResult Runtime::StoreRemote(
    melonDS::u32 frame,
    const InputState& input,
    std::optional<melonDS::u32> localFrame,
    bool confirmPrediction,
    melonDS::u32 noFrameLimit)
{
    RemoteInputStoreResult result;
    result.PreviousLastReceived = LastReceivedInputFrame;
    if (confirmPrediction)
        result.Confirmation = RollbackInputs.Confirm(frame, input, localFrame);
    RemoteInputs[frame] = input;
    if (LastReceivedInputFrame == noFrameLimit || LastReceivedInputFrame < frame)
        LastReceivedInputFrame = frame;
    return result;
}

void Runtime::PruneHistory(melonDS::u32 keepFromFrame)
{
    LocalInputs.erase(LocalInputs.begin(), LocalInputs.lower_bound(keepFromFrame));
    RemoteInputs.erase(RemoteInputs.begin(), RemoteInputs.lower_bound(keepFromFrame));
}

void Runtime::PrimeEpoch(
    melonDS::u32 startFrame,
    melonDS::u32 delay,
    const InputState& neutralInput,
    melonDS::u32 noFrameLimit)
{
    PruneHistory(startFrame);
    const melonDS::u32 firstInputFrame = startFrame + delay;
    for (melonDS::u32 frame = startFrame; frame < firstInputFrame; frame++)
    {
        LocalInputs.emplace(frame, neutralInput);
        RemoteInputs.emplace(frame, neutralInput);
    }
    if (delay == 0)
        return;

    const melonDS::u32 primedThrough = firstInputFrame - 1;
    if (LastReceivedInputFrame == noFrameLimit || LastReceivedInputFrame < primedThrough)
        LastReceivedInputFrame = primedThrough;
}

int Runtime::Lead(melonDS::u32 sendFrame, melonDS::u32 noFrameLimit) const
{
    if (LastReceivedInputFrame == noFrameLimit)
        return 0;
    return static_cast<int>(sendFrame) - static_cast<int>(LastReceivedInputFrame);
}

void Runtime::RecordRemoteInputWait(unsigned long long elapsedUs, unsigned long long loops)
{
    RemoteInputWaitCount++;
    RemoteInputWaitLoops += loops;
    RemoteInputWaitUs += elapsedUs;
    RemoteInputWaitMaxUs = std::max(RemoteInputWaitMaxUs, elapsedUs);
}

void Runtime::RecordFrameLeadThrottle(unsigned long long elapsedUs, unsigned long long loops)
{
    FrameLeadThrottleCount++;
    FrameLeadThrottleLoops += loops;
    FrameLeadThrottleUs += elapsedUs;
    FrameLeadThrottleMaxUs = std::max(FrameLeadThrottleMaxUs, elapsedUs);
}

std::optional<ReplayFrameInputs> ResolveReplayFrameInputs(
    Runtime& runtime,
    melonDS::u32 frame,
    int localPlayer,
    const InputState& neutralInput,
    const PredictionProbe& probe)
{
    if (localPlayer < 0 || localPlayer > 1)
        return std::nullopt;

    ReplayFrameInputs result;
    const auto local = runtime.LocalInputs.find(frame);
    if (local != runtime.LocalInputs.end())
        result.Local = local->second;
    else
        result.Local = neutralInput;

    const PredictedInput remote = runtime.RollbackInputs.Resolve(
        frame, runtime.RemoteInputs, neutralInput, probe);
    result.Remote = remote.Input;
    result.RemotePredicted = remote.Predicted;
    result.Players[localPlayer] = result.Local;
    result.Players[1 - localPlayer] = result.Remote;
    return result;
}

bool ParseInputSpec(const std::string& spec, InputState& input)
{
    input = {};

    if (spec.empty() || Upper(spec) == "NONE" || Upper(spec) == "NEUTRAL")
        return true;

    if (spec.rfind("mask=", 0) == 0 || spec.rfind("MASK=", 0) == 0)
    {
        melonDS::u32 mask = 0;
        if (!ParseU32(spec.substr(5), mask))
            return false;
        input.KeyMask = mask & 0xFFF;
        return true;
    }

    std::stringstream stream(spec);
    std::string button;
    while (std::getline(stream, button, '+'))
    {
        const int bit = ButtonBit(Trim(button));
        if (bit < 0)
            return false;
        input.KeyMask &= ~(1u << bit);
    }
    return true;
}

bool ParseInputScript(std::istream& input, std::vector<InputSpan>& spans, ParseError& error)
{
    spans.clear();
    error = {};

    std::string line;
    int lineNo = 0;
    while (std::getline(input, line))
    {
        lineNo++;
        const auto comment = line.find('#');
        if (comment != std::string::npos)
            line.resize(comment);
        line = Trim(line);
        if (line.empty())
            continue;

        std::stringstream stream(line);
        std::string target;
        std::string range;
        std::string buttons;
        std::string touch;
        stream >> target >> range >> buttons >> touch;

        InputSpan span;
        if (target.find('-') != std::string::npos)
        {
            touch = buttons;
            buttons = range;
            range = target;
        }
        else
        {
            const std::string upperTarget = Upper(target);
            if (upperTarget != "ALL")
            {
                constexpr const char* prefix = "INST";
                melonDS::u32 targetInstance = 0;
                if (upperTarget.rfind(prefix, 0) != 0 ||
                    !ParseU32(upperTarget.substr(4), targetInstance) ||
                    targetInstance >= 16)
                {
                    error = { ParseErrorKind::Target, lineNo };
                    return false;
                }
                span.Instance = static_cast<int>(targetInstance);
            }
        }

        const auto dash = range.find('-');
        if (dash == std::string::npos)
        {
            error = { ParseErrorKind::Range, lineNo };
            return false;
        }
        if (!ParseU32(range.substr(0, dash), span.Start) ||
            !ParseU32(range.substr(dash + 1), span.End) ||
            span.End < span.Start ||
            !ParseInputSpec(buttons, span.Input))
        {
            error = { ParseErrorKind::Input, lineNo };
            return false;
        }

        if (!touch.empty())
        {
            const auto comma = touch.find(',');
            melonDS::u32 x = 0;
            melonDS::u32 y = 0;
            if (comma == std::string::npos ||
                !ParseU32(touch.substr(0, comma), x) ||
                !ParseU32(touch.substr(comma + 1), y))
            {
                error = { ParseErrorKind::Touch, lineNo };
                return false;
            }
            span.Input.Touching = true;
            span.Input.TouchX = static_cast<melonDS::u16>(std::min<melonDS::u32>(x, 255));
            span.Input.TouchY = static_cast<melonDS::u16>(std::min<melonDS::u32>(y, 191));
        }
        spans.push_back(span);
    }
    return true;
}

bool LoadInputScriptFile(
    const std::string& path,
    std::vector<InputSpan>& spans,
    ParseError& error)
{
    std::ifstream file(path);
    if (!file)
    {
        spans.clear();
        error = { ParseErrorKind::Open, 0 };
        return false;
    }
    return ParseInputScript(file, spans, error);
}

InputState Apply(
    const std::vector<InputSpan>& spans,
    int instanceID,
    melonDS::u32 frame,
    const InputState& fallback)
{
    for (const InputSpan& span : spans)
    {
        if ((span.Instance < 0 || span.Instance == instanceID) &&
            frame >= span.Start && frame <= span.End)
        {
            return span.Input;
        }
    }
    return fallback;
}

