std::string Trim(std::string value)
{
    const auto first = value.find_first_not_of(" \t\r\n");
    if (first == std::string::npos)
        return {};
    const auto last = value.find_last_not_of(" \t\r\n");
    return value.substr(first, last - first + 1);
}

std::string Upper(std::string value)
{
    for (char& ch : value)
        ch = static_cast<char>(std::toupper(static_cast<unsigned char>(ch)));
    return value;
}

bool ParseU32(const std::string& text, melonDS::u32& out)
{
    char* end = nullptr;
    const unsigned long value = std::strtoul(text.c_str(), &end, 0);
    if (!end || *end != '\0')
        return false;
    out = static_cast<melonDS::u32>(value);
    return true;
}

int ButtonBit(const std::string& name)
{
    const std::string key = Upper(name);
    if (key == "A") return 0;
    if (key == "B") return 1;
    if (key == "SELECT") return 2;
    if (key == "START") return 3;
    if (key == "RIGHT") return 4;
    if (key == "LEFT") return 5;
    if (key == "UP") return 6;
    if (key == "DOWN") return 7;
    if (key == "R") return 8;
    if (key == "L") return 9;
    if (key == "X") return 10;
    if (key == "Y") return 11;
    return -1;
}

bool InputsEqual(const InputState& left, const InputState& right)
{
    return left.KeyMask == right.KeyMask
        && left.Touching == right.Touching
        && left.TouchX == right.TouchX
        && left.TouchY == right.TouchY;
}

std::string InputSpecForScript(const InputState& input)
{
    static constexpr const char* kButtonNames[12] {
        "A",
        "B",
        "SELECT",
        "START",
        "RIGHT",
        "LEFT",
        "UP",
        "DOWN",
        "R",
        "L",
        "X",
        "Y",
    };

    std::string spec;
    for (int bit = 0; bit < 12; bit++)
    {
        if ((input.KeyMask & (1u << bit)) != 0)
            continue;
        if (!spec.empty())
            spec += "+";
        spec += kButtonNames[bit];
    }
    if (spec.empty())
        spec = "NONE";
    if (input.Touching)
    {
        spec += " ";
        spec += std::to_string(input.TouchX);
        spec += ",";
        spec += std::to_string(input.TouchY);
    }
    return spec;
}

