Recorder::~Recorder()
{
    Close();
}

bool Recorder::Open(
    const std::string& path,
    melonDS::u32 startFrame,
    melonDS::u32 endFrame,
    int instanceID)
{
    Close();
    std::lock_guard<std::mutex> lock(Mutex_);
    Output_.open(path, std::ios::out | std::ios::trunc);
    if (!Output_)
        return false;

    StartFrame_ = startFrame;
    EndFrame_ = endFrame;
    InstanceID_ = instanceID;
    HasSpan_ = false;
    PendingSpans_ = 0;
    Output_ << "# NSMB input recording generated by melonDS NSML PoC\n";
    Output_ << "# startFrame=" << StartFrame_
        << " endFrame=" << EndFrame_
        << " instance=" << InstanceID_ << "\n";
    Output_.flush();
    Enabled_.store(true, std::memory_order_release);
    return true;
}

bool Recorder::IsOpen() const
{
    return Enabled_.load(std::memory_order_acquire);
}

void Recorder::Record(int instanceID, melonDS::u32 frame, const InputState& input)
{
    if (!Enabled_.load(std::memory_order_acquire))
        return;
    std::lock_guard<std::mutex> lock(Mutex_);
    if (!Output_)
        return;
    if (InstanceID_ >= 0 && InstanceID_ != instanceID)
        return;
    if (frame < StartFrame_ || (EndFrame_ != 0 && frame > EndFrame_))
        return;

    InputState recordInput = input;
    recordInput.KeyMask &= 0xFFF;
    if (!HasSpan_)
    {
        SpanStart_ = frame;
        SpanEnd_ = frame;
        SpanInput_ = recordInput;
        HasSpan_ = true;
        return;
    }

    if (SpanEnd_ + 1 == frame && InputsEqual(SpanInput_, recordInput))
    {
        SpanEnd_ = frame;
        return;
    }
    if (frame <= SpanEnd_)
    {
        if (!InputsEqual(SpanInput_, recordInput)
            && SpanStart_ == frame
            && SpanEnd_ == frame)
        {
            SpanInput_ = recordInput;
        }
        return;
    }

    FlushSpanLocked();
    SpanStart_ = frame;
    SpanEnd_ = frame;
    SpanInput_ = recordInput;
    HasSpan_ = true;
}

void Recorder::Close()
{
    Enabled_.store(false, std::memory_order_release);
    std::lock_guard<std::mutex> lock(Mutex_);
    FlushSpanLocked();
    if (Output_.is_open())
        Output_.close();
}

void Recorder::FlushSpanLocked()
{
    if (!Output_ || !HasSpan_)
        return;

    Output_ << SpanStart_ << "-" << SpanEnd_ << " "
        << InputSpecForScript(SpanInput_) << "\n";
    HasSpan_ = false;
    PendingSpans_++;
    if (PendingSpans_ >= 64)
    {
        Output_.flush();
        PendingSpans_ = 0;
    }
}

ConfirmedInputResult PredictionRuntime::Confirm(
    melonDS::u32 frame,
    const InputState& input,
    std::optional<melonDS::u32> localFrame)
{
    ConfirmedInputResult result;
    const auto predicted = Predictions_.find(frame);
    if (predicted != Predictions_.end() && !InputsEqual(predicted->second, input))
    {
        result.Mismatch = true;
        result.PredictedInput = predicted->second;
        result.FrameAlreadySimulated = !localFrame || frame < *localFrame;
        MismatchCount_++;

        if (result.FrameAlreadySimulated)
        {
            const melonDS::u32 observedFrame = localFrame.value_or(frame);
            if (!PendingRollbackFrame_ || frame < *PendingRollbackFrame_)
            {
                PendingRollbackFrame_ = frame;
                PendingRollbackObservedFrame_ = observedFrame;
            }
            else if (!PendingRollbackObservedFrame_)
            {
                PendingRollbackObservedFrame_ = observedFrame;
            }
        }
        Predictions_.erase(Predictions_.lower_bound(frame), Predictions_.end());
        PredictionProbeConfirmations_.erase(
            PredictionProbeConfirmations_.lower_bound(frame),
            PredictionProbeConfirmations_.end());
    }

    PredictionProbeConfirmations_.erase(frame);

    LastConfirmedInput_ = input;
    return result;
}

PredictedInput PredictionRuntime::Resolve(
    melonDS::u32 frame,
    const InputMap& confirmedInputs,
    const InputState& neutralInput,
    const PredictionProbe& probe)
{
    const bool belowProbeLimit = probe.Limit < 0
        || PredictionProbeCount_ < static_cast<melonDS::u32>(probe.Limit);
    const bool insideProbeRange = frame >= probe.StartFrame
        && (!probe.EndFrame || frame <= *probe.EndFrame);
    const bool applyProbe = probe.Modulo > 0
        && belowProbeLimit
        && insideProbeRange
        && (frame % static_cast<melonDS::u32>(probe.Modulo))
            == static_cast<melonDS::u32>(probe.Offset);

    const auto confirmed = confirmedInputs.find(frame);
    if (confirmed != confirmedInputs.end())
    {
        if (applyProbe && probe.ConfirmAfterOneFrame)
        {
            InputState input = confirmed->second;
            PredictionProbeConfirmations_[frame] = input;
            input.KeyMask ^= probe.KeyMask & 0xFFFu;
            Predictions_[frame] = input;
            PredictionProbeCount_++;
            PredictionCount_++;
            return { input, true };
        }
        return { confirmed->second, false };
    }

    const auto existing = Predictions_.find(frame);
    if (existing != Predictions_.end())
        return { existing->second, true };

    InputState input = neutralInput;
    const auto previous = frame > 0
        ? Predictions_.find(frame - 1)
        : Predictions_.end();
    if (previous != Predictions_.end())
        input = previous->second;
    else if (LastConfirmedInput_)
        input = *LastConfirmedInput_;

    if (applyProbe)
    {
        if (probe.ConfirmAfterOneFrame)
            PredictionProbeConfirmations_.emplace(frame, input);
        input.KeyMask ^= probe.KeyMask & 0xFFFu;
        PredictionProbeCount_++;
    }

    Predictions_.emplace(frame, input);
    PredictionCount_++;
    return { input, true };
}

void PredictionRuntime::Prune(
    melonDS::u32 currentFrame,
    melonDS::u32 window,
    const InputMap& confirmedInputs)
{
    const melonDS::u32 keepFrom = currentFrame > window ? currentFrame - window : 0;
    for (auto prediction = Predictions_.begin(); prediction != Predictions_.end();)
    {
        if (prediction->first < keepFrom
            && confirmedInputs.find(prediction->first) != confirmedInputs.end())
        {
            prediction = Predictions_.erase(prediction);
        }
        else
        {
            ++prediction;
        }
    }
}

void PredictionRuntime::ClearPredictions()
{
    Predictions_.clear();
    PredictionProbeConfirmations_.clear();
}

std::optional<InputState> PredictionRuntime::TakePredictionProbeConfirmation(
    melonDS::u32 frame)
{
    const auto confirmation = PredictionProbeConfirmations_.find(frame);
    if (confirmation == PredictionProbeConfirmations_.end())
        return std::nullopt;

    const InputState input = confirmation->second;
    PredictionProbeConfirmations_.erase(confirmation);
    return input;
}

